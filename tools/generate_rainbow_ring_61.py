"""Generate a seamless, rotating HSV rainbow for the cpx_ring_61 layout.

The YAML is the editable frame-based format accepted by weapon_fsm_lights.
The binary SD assets are subsequently generated by the normal SD exporter.
Choose either the inside-out or outside-in layout when generating the sequence.
"""

from __future__ import annotations

import argparse
import colorsys
import json
import math
from pathlib import Path

import yaml


FRAME_COUNT = 60
FRAME_DURATION_MS = 50
BRIGHTNESS = 0.32


def make_rainbow(layout_path: Path) -> dict:
    layout = json.loads(layout_path.read_text(encoding="utf-8"))
    leds = sorted(layout["leds"], key=lambda entry: entry["index"])
    indices = [entry["index"] for entry in leds]
    if indices != list(range(61)):
        raise ValueError("This animation requires the cpx_ring_61 layout with LED indices 0 through 60")

    frames = []
    for frame_number in range(FRAME_COUNT):
        frame_leds: dict[str, dict[str, float | str]] = {}
        for led in leds:
            x = float(led["u"]) - 0.5
            y = float(led["v"]) - 0.5
            # One rainbow wraps around each ring. A radial phase makes the
            # concentric rings form a slowly rotating spiral pattern.
            angle = (math.atan2(y, x) / (2.0 * math.pi)) % 1.0
            radius = min(math.hypot(x, y) / 0.49, 1.0)
            hue = (angle + radius * 0.18 - frame_number / FRAME_COUNT) % 1.0
            red, green, blue = colorsys.hsv_to_rgb(hue, 1.0, 1.0)
            color = f"#{round(red * 255):02x}{round(green * 255):02x}{round(blue * 255):02x}"
            frame_leds[str(led["index"])] = {"color": color, "intensity": BRIGHTNESS}
        frames.append({"duration_ms": FRAME_DURATION_MS, "leds": frame_leds})

    return {
        "layout": {"path": f"layouts/{layout_path.name}"},
        "frames": frames,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate a looping 61-LED rainbow light sequence")
    parser.add_argument("--layout", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    payload = make_rainbow(args.layout)
    args.output.write_text(yaml.safe_dump(payload, sort_keys=False, width=120), encoding="utf-8")
    print(f"Wrote {len(payload['frames'])} frames ({FRAME_COUNT * FRAME_DURATION_MS} ms) to {args.output}")


if __name__ == "__main__":
    main()
